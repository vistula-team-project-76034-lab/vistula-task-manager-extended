-- Vistula Task Manager Extended – database schema
-- Run in Supabase → SQL Editor (separate demonstration project).
--
-- Relationship: ONE category  →  MANY tasks
--   categories.id  (primary key)
--   tasks.category_id  (foreign key → categories.id)

-- 1. Table "categories"
create table if not exists public.categories (
  id   bigint generated by default as identity primary key,
  name text not null
);

-- 2. Table "tasks" with a foreign key to "categories"
create table if not exists public.tasks (
  id          bigint generated by default as identity primary key,
  title       text    not null,
  description text,
  completed   boolean not null default false,
  category_id bigint references public.categories (id) on delete restrict
);

-- Index on the foreign key (speeds up filtering by category)
create index if not exists tasks_category_id_idx on public.tasks (category_id);

-- 3. Permissions for the public (publishable key / anon) role
grant usage on schema public to anon;
grant select, insert on table public.categories to anon;
grant select, insert, update, delete on table public.tasks to anon;
grant usage, select on all sequences in schema public to anon;

-- 4. Row Level Security
alter table public.categories enable row level security;
alter table public.tasks      enable row level security;

drop policy if exists "Public read categories"   on public.categories;
drop policy if exists "Public insert categories" on public.categories;
create policy "Public read categories"   on public.categories for select to anon using (true);
create policy "Public insert categories" on public.categories for insert to anon with check (true);

drop policy if exists "Public read tasks"   on public.tasks;
drop policy if exists "Public insert tasks" on public.tasks;
drop policy if exists "Public update tasks" on public.tasks;
drop policy if exists "Public delete tasks" on public.tasks;
create policy "Public read tasks"   on public.tasks for select to anon using (true);
create policy "Public insert tasks" on public.tasks for insert to anon with check (true);
create policy "Public update tasks" on public.tasks for update to anon using (true) with check (true);
create policy "Public delete tasks" on public.tasks for delete to anon using (true);

